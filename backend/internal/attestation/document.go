package attestation

import (
	"bytes"
	"context"
	"strings"
	"time"

	"github.com/go-pdf/fpdf"
)

// Facts are the names a generated certificate prints, read for one Input.
type Facts struct {
	Issuer, Subject, IssuedAt string
}

// Facts reads the issuer's name, the subject's label (lot code or facility
// name) and the issued-at facility's name.
func (s Store) Facts(ctx context.Context, orgID string, in Input) (Facts, error) {
	var f Facts
	err := s.Pool.QueryRow(ctx,
		`SELECT COALESCE((SELECT name FROM organisations WHERE id = $1::uuid), ''),
		        COALESCE(CASE WHEN $2 = '`+SubjectPassport+`'
		                      THEN (SELECT code FROM passports WHERE id = $3::uuid)
		                      ELSE (SELECT name FROM facilities WHERE id = $3::uuid) END, ''),
		        COALESCE((SELECT name FROM facilities WHERE id = NULLIF($4, '')::uuid), '')`,
		orgID, in.SubjectType, in.SubjectID, in.IssuedAt).Scan(&f.Issuer, &f.Subject, &f.IssuedAt)
	return f, err
}

// DocumentName is the file name of a generated certificate.
func DocumentName(certType string) string { return certType + "-certificate.pdf" }

// Document is the certificate ChainTrack writes when the issuer uploads none:
// one A4 page of what was certified. Its SHA-256 is anchored like an upload's.
func Document(in Input, f Facts, now time.Time) ([]byte, error) {
	doc := fpdf.New("P", "mm", "A4", "")
	tr := doc.UnicodeTranslatorFromDescriptor("") // cp1252: accents in names survive
	doc.SetMargins(20, 20, 20)
	doc.AddPage()
	doc.SetFont("Helvetica", "B", 20)
	doc.CellFormat(0, 12, tr("Certificate · "+humanize(in.Type)), "", 1, "L", false, 0, "")
	doc.SetFont("Helvetica", "", 10)
	doc.CellFormat(0, 6, tr("Issued by "+f.Issuer+" on "+now.UTC().Format("2 January 2006")), "", 1, "L", false, 0, "")
	doc.Ln(6)

	subject := "Lot"
	if in.SubjectType == SubjectFacility {
		subject = "Facility"
	}
	rows := [][2]string{
		{subject, f.Subject},
		{"Certificate type", humanize(in.Type)},
		{"Valid from", in.ValidFrom.UTC().Format("2 January 2006")},
		{"Valid until", in.ValidTo.UTC().Format("2 January 2006")},
	}
	if in.CertNumber != "" {
		rows = append(rows, [2]string{"Certificate number", in.CertNumber})
	}
	if f.IssuedAt != "" {
		rows = append(rows, [2]string{"Issued at", f.IssuedAt})
	}
	for _, r := range rows {
		doc.SetFont("Helvetica", "B", 11)
		doc.CellFormat(50, 8, tr(r[0]), "", 0, "L", false, 0, "")
		doc.SetFont("Helvetica", "", 11)
		doc.CellFormat(0, 8, tr(r[1]), "", 1, "L", false, 0, "")
	}
	if in.Notes != "" {
		doc.Ln(4)
		doc.SetFont("Helvetica", "B", 11)
		doc.CellFormat(0, 8, "Notes", "", 1, "L", false, 0, "")
		doc.SetFont("Helvetica", "", 11)
		doc.MultiCell(0, 6, tr(in.Notes), "", "L", false)
	}
	doc.Ln(10)
	doc.SetFont("Helvetica", "I", 9)
	doc.MultiCell(0, 5, tr("Generated by ChainTrack. This document's fingerprint is sealed on the ledger; "+
		"check it on the record's public verification page."), "", "L", false)

	var out bytes.Buffer
	err := doc.Output(&out)
	return out.Bytes(), err
}

// humanize prints a key: export_permit → Export permit.
func humanize(key string) string {
	s := strings.ReplaceAll(key, "_", " ")
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
